    /// Uncomment the template's key/value and table-header lines (first
    /// non-`#` content is a snake_case identifier followed by `=`, or a `[`),
    /// leaving prose lines commented — simulating a user who enabled every
    /// setting at once.
    fn uncomment_template(template: &str) -> String {
        template
            .lines()
            .map(|line| {
                let Some(body) = line.strip_prefix('#') else {
                    return line;
                };
                let t = body.trim_start();
                let ident: usize = t
                    .chars()
                    .take_while(|c| c.is_ascii_lowercase() || *c == '_' || c.is_ascii_digit())
                    .count();
                let starts_kv = ident > 0 && t[ident..].trim_start().starts_with('=');
                if t.starts_with('[') || starts_kv {
                    body
                } else {
                    line
                }
            })
            .collect::<Vec<_>>()
            .join("\n")
    }

    #[test]
    fn uncommented_template_parses_and_top_level_keys_precede_tables() {
        // TOML rule: after a table header, bare keys belong to that table. If
        // a top-level key ever drifts below one in DEFAULT_TEMPLATE, this
        // parse fails on unknown fields (or silently swallows keys into
        // [[mcp_servers]] entries, caught by the spot checks below).
        let enabled = uncomment_template(DEFAULT_TEMPLATE);
        let cfg = build_config(toml::from_str::<RawConfig>(&enabled).expect(
            "fully-uncommented template must parse; \
             suspect a top-level key below a [table] header",
        ))
        .expect("uncommented template should build");

        assert_eq!(cfg.model, "deepseek-v4-flash");
        assert_eq!(cfg.max_tokens, 4096);
        assert_eq!(cfg.max_turns, 20);
        // Would be None/absent if these keys were swallowed by a table above.
        assert_eq!(cfg.log_dir, Some("ma-logs".into()));
        assert_eq!(cfg.system_prefix, Some(String::new()));
        assert_eq!(cfg.mcp_list_tools_timeout_ms, 10_000);
        // The tables themselves still landed where they belong.
        assert!(cfg.reasoning.thinking_enabled);
        assert_eq!(
            cfg.reasoning.effort,
            ReasoningEffortOverride::Set("max".into())
        );
        assert_eq!(cfg.mcp_servers.len(), 2);
    }

