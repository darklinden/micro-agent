//! TOML-file-driven configuration (`~/.ma/config.toml`).
//!
//! Mirrors the `ai-bridge` config convention (ADR-0005 there, ADR-0008 here):
//! one single file holds everything — the upstream format is declared
//! explicitly via `upstream_type` (never guessed from the URL), agent
//! behaviour is tuned through optional snake_case keys, unknown keys fail
//! startup (`deny_unknown_fields`), and a missing file drops a
//! fully-commented starter template next to the precise "missing field"
//! error instead of silently serving placeholder values. Only `$HOME` is
//! still read from the environment — to resolve the config path.

use crate::mcp::McpServerConfig;
use anyhow::{anyhow, Result};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Configuration lives in `~/.ma/<CONFIG_FILE_NAME>` (ADR-0008). The former
/// `MA_*` environment variables are gone; `$HOME` is the only environment
/// read, solely to resolve this path.
pub(crate) const CONFIG_DIR_NAME: &str = ".ma";
pub(crate) const CONFIG_FILE_NAME: &str = "config.toml";

const DEFAULT_MAX_TOKENS: usize = 128000;
const DEFAULT_MAX_TURNS: usize = 256;
const DEFAULT_MAX_TOOL_RESULT_BYTES: usize = 32 * 1024;
const DEFAULT_MCP_LIST_TOOLS_TIMEOUT_MS: u64 = 10_000;

/// Fully-commented starter template dropped as the requested config file when
/// it does not exist. Every value line is commented so the next launch fails
/// with a precise "missing field" error instead of silently running on
/// placeholder values.
///
/// Ordering matters (TOML rule): every top-level key comes BEFORE any table
/// header — after `[headers]`, bare keys would be parsed as members of that
/// table. The template therefore keeps all scalars up top and pins the three
/// tables to the bottom; a unit test uncomments the template and parses it so
/// this invariant cannot regress.
const DEFAULT_TEMPLATE: &str = r#"# ma config — this file is auto-generated by ma;
# fill in the required fields below and you're ready to start.
#
# Usage:
#   ma                 loads ~/.ma/config.toml (this file)
#   ma --config FILE   loads FILE instead
#
# Every line is commented out — uncomment and fill in real values before
# launching. Unknown keys are rejected at startup, so a typo can never
# silently disable a setting.
#
# TOML ordering: top-level keys MUST stay above the [tables] at the bottom —
# after a table header, bare keys become part of that table.

# ===================== Required =====================

# Upstream API format, one of: anthropic-messages | oai-chat
# It explicitly decides the auth header and wire format — no URL guessing.
#upstream_type = "oai-chat"

# Upstream API endpoint (matching the upstream_type)
#url = "https://api.example.com/v1"

# Upstream API key (OpenAI-family upstreams use Authorization: Bearer;
# Anthropic upstreams use x-api-key)
#api_key = "sk-your-upstream-key"

# ================= Optional top-level keys =================

# Model id. Default follows upstream_type: oai-chat -> deepseek-v4-flash,
# anthropic-messages -> claude-sonnet-4-5.
#model = "deepseek-v4-flash"

# Max output tokens per assistant turn. Default: 128000
#max_tokens = 128000

# Tool-loop iterations before giving up (exit 2). Default: 256
#max_turns = 256

# Turn budget for each `task` sub-agent. Default: inherits max_turns
#task_max_turns = 256

# Tools that must never run (refused before every execution path).
#deny_tools = ["bash"]

# Bash safety gate. Default: true; set false for pure-auto mode.
#gate = true

# Cap on tool output fed back into context. Default: 32768
#max_tool_result_bytes = 32768

# Per-server MCP connect + list_tools timeout in ms. Default: 10000
#mcp_list_tools_timeout_ms = 10000

# Directory for per-launch JSONL session logs (<yyyymmdd-HHmmss>.log).
# Unset = nothing is written.
#log_file_dir = ".ma-logs"

# Write threshold: debug | info | warn | error. Default: info
#log_level = "info"

# System prompt values — each may be a literal string OR a file path whose
# contents are inlined (point system_suffix at a CLAUDE.md to inject repo
# context).

# Prepended to the system prompt.
#system_prefix = ""

# Appended to the system prompt.
#system_suffix = ""

# Replaces the built-in persona entirely.
#persona = ""

# Replaces the whole prefix+persona+suffix composite.
#system_prompt = ""

# ================= Tables (keep these LAST) =================

# Extra request headers applied to every upstream request.
#[headers]
#X-Tenant = "default"

# Outbound reasoning parameter policy.
#[reasoning]
#thinking = true       # master switch, default true; when off, ALL reasoning params are stripped from outbound requests
#effort = "max"        # default max; off/drop/none/disable/disabled = drop the whole field;
#                      # any other value is trimmed, lowercased, and passed through as-is

# One [[mcp_servers]] table per server: stdio needs cmd (+ args/env),
# SSE needs url. A server that fails to connect is skipped, not fatal.
#[[mcp_servers]]
#name = "fs"
#cmd = "npx"
#args = ["-y", "@modelcontextprotocol/server-fs"]
#env = { KEY = "value" }

#[[mcp_servers]]
#name = "remote"
#url = "https://mcp.example.com/sse"
"#;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UpstreamType {
    AnthropicMessages,
    OaiChat,
}

impl UpstreamType {
    fn parse(s: &str) -> Result<Self> {
        match s {
            "anthropic-messages" => Ok(UpstreamType::AnthropicMessages),
            "oai-chat" => Ok(UpstreamType::OaiChat),
            other => Err(anyhow!(
                "invalid upstream_type {other:?}: expected \"anthropic-messages\" or \"oai-chat\""
            )),
        }
    }

    fn default_model(self) -> &'static str {
        match self {
            UpstreamType::AnthropicMessages => "claude-sonnet-4-5",
            UpstreamType::OaiChat => "deepseek-v4-flash",
        }
    }
}

/// What to do with the outgoing reasoning-effort field (`reasoning_effort`
/// on Chat Completions): stamp this exact value (lowercased) or omit the
/// field entirely. Ported from the ai-bridge `[reasoning]` convention — the
/// configured value is the single source of truth, no per-model mapping is
/// applied on top of it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReasoningEffortOverride {
    Set(String),
    Drop,
}

/// Outbound reasoning policy resolved once at startup from the `[reasoning]`
/// config table:
/// - `thinking_enabled == false` (master switch off): all thinking affordances
///   are stripped from outgoing requests and `effort` is ignored;
/// - otherwise the effort override decides the outgoing effort value.
#[derive(Debug, Clone)]
pub struct ReasoningPolicy {
    /// Master switch from `[reasoning] thinking` (default on).
    pub thinking_enabled: bool,
    /// Effort policy from `[reasoning] effort` (default `max`).
    pub effort: ReasoningEffortOverride,
}

impl ReasoningPolicy {
    /// Resolve the policy from raw table values. Defaults: thinking on,
    /// effort `"max"`; the Drop keyword set mirrors ai-bridge exactly.
    fn parse(thinking: Option<bool>, effort: Option<&str>) -> Self {
        let thinking_enabled = thinking.unwrap_or(true);
        let effort = match effort.map(str::trim).filter(|v| !v.is_empty()) {
            None => ReasoningEffortOverride::Set("max".into()),
            Some(raw) => match raw.to_ascii_lowercase().as_str() {
                "off" | "drop" | "none" | "disable" | "disabled" => ReasoningEffortOverride::Drop,
                _ => ReasoningEffortOverride::Set(raw.to_ascii_lowercase()),
            },
        };
        Self {
            thinking_enabled,
            effort,
        }
    }

    /// The `reasoning_effort` value to emit for an `oai-chat` request under
    /// this policy, or `None` to omit the field entirely.
    pub fn audience_effort(&self) -> Option<&str> {
        if !self.thinking_enabled {
            return None;
        }
        match &self.effort {
            ReasoningEffortOverride::Set(v) => Some(v),
            ReasoningEffortOverride::Drop => None,
        }
    }
}

#[derive(Debug, Clone)]
pub struct Config {
    pub upstream_type: UpstreamType,
    pub url: String,
    pub api_key: String,
    pub model: String,
    pub max_tokens: usize,
    pub reasoning: ReasoningPolicy,
    /// Extra headers applied to every upstream request, e.g. `Name: value`.
    pub extra_headers: Vec<(String, String)>,

    // Agent behaviour
    pub max_turns: usize,
    /// Turn budget for a `task` sub-agent; `None` inherits `max_turns`.
    pub task_max_turns: Option<usize>,
    /// Names of tools that must not be invoked (e.g. `["bash"]`).
    pub deny_tools: Vec<String>,
    /// Whether the LLM safety gate guards `bash` execution. `gate = false` disables.
    pub gate_enabled: bool,
    /// Byte threshold for tool results: results at or below this size pass
    /// through to the model unchanged; larger ones are compressed by a separate
    /// LLM call (`max_tool_result_bytes`).
    pub max_tool_result_bytes: usize,

    // MCP
    pub mcp_servers: Vec<McpServerConfig>,
    pub mcp_list_tools_timeout_ms: u64,

    // System prompt
    pub system_prefix: Option<String>,
    pub system_suffix: Option<String>,
    pub persona: Option<String>,
    /// When set, REPLACES the whole prefix+persona+suffix composite
    /// (`system_prompt`; string or file path).
    pub system_prompt: Option<String>,

    // Logging
    pub log_dir: Option<PathBuf>,
    pub log_level: String,
}

/// Resolve the default config path: `$HOME/.ma/config.toml` (ADR-0008).
pub fn default_path() -> Result<PathBuf> {
    config_path(std::env::var("HOME").ok().as_deref())
}

/// Injected variant of [`default_path`] so tests never mutate `$HOME`.
fn config_path(home: Option<&str>) -> Result<PathBuf> {
    match home.map(str::trim).filter(|h| !h.is_empty()) {
        Some(home) => Ok(Path::new(home).join(CONFIG_DIR_NAME).join(CONFIG_FILE_NAME)),
        None => Err(anyhow!(
            "HOME environment variable is not set; cannot resolve ~/.ma/{CONFIG_FILE_NAME}"
        )),
    }
}

/// Load and parse the config file at `path`. A missing file surfaces an error
/// that — best effort — drops the commented starter template at the same path
/// so first-time users have something concrete to edit.
pub fn load(path: &Path) -> Result<Config> {
    let text = match std::fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return Err(missing_config_error(path));
        }
        Err(e) => return Err(anyhow!("failed to read config {}: {e}", path.display())),
    };

    let raw: RawConfig = toml::from_str(&text).map_err(|e| {
        anyhow!("invalid config {}: {e}", path.display())
    })?;
    build_config(raw)
}

/// Build the not-found error, attempting to leave a starter template behind
/// so first-time users have something concrete to edit. Template failures are
/// warned about on stderr (the session logger is not up yet), never masking
/// the original error.
fn missing_config_error(path: &Path) -> anyhow::Error {
    let mut msg = format!("config not found: {}", path.display());
    match write_starter_template(path) {
        Ok(true) => msg.push_str(
            "; a starter template was written to that path — \
             fill in the required keys and rerun",
        ),
        Ok(false) => {}
        Err(e) => eprintln!("warning: could not write starter template: {e}"),
    }
    anyhow!(msg)
}

/// Ensure the parent directory exists and drop the commented starter template
/// at `path`. Returns whether a new file was written; never overwrites.
fn write_starter_template(path: &Path) -> std::io::Result<bool> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    if path.exists() {
        return Ok(false);
    }
    std::fs::write(path, DEFAULT_TEMPLATE)?;
    Ok(true)
}

